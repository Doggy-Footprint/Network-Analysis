"""V09: Q01 (time to a stabilised graph) and Q02 (click to dialog visible) on the real tag-manager report.

Measured in five fresh Chromium contexts at 1440x900 with the CDN URL served from the local vis-network copy (A08).
The generated report and raw readings are recorded in tests/report_redesign_evidence/browser.json.
"""
import hashlib
import statistics
import subprocess
import sys
import time
from pathlib import Path

import pytest

from tests.report_redesign_support import SEL, click_graph_node, dialog, graph_data, prepare_canvas, record
from tests.unified_support import CDN_URL, GRAPH_READY, VIS_FILE

ROOT = Path(__file__).resolve().parents[1]
TAG_MANAGER = Path.home() / 'toy-projects' / 'tag-manager'
Q01_LIMIT_MS = 5000
Q02_LIMIT_MS = 300

CLICK_TO_DIALOG_JS = """() => new Promise((resolve) => {
  const visible = () => { const d = document.querySelector('[role=dialog]'); return !!d && d.getBoundingClientRect().height > 0 && getComputedStyle(d).visibility !== 'hidden'; };
  document.addEventListener('pointerup', () => {
    const t0 = performance.now();
    const tick = () => visible() ? resolve(performance.now() - t0) : (performance.now() - t0 > 10000 ? resolve(-1) : requestAnimationFrame(tick));
    tick();
  }, {capture: true, once: true});
})"""


@pytest.fixture(scope='module')
def tag_manager_html(tmp_path_factory):
    if not TAG_MANAGER.is_dir():
        pytest.skip(f'{TAG_MANAGER} is not available on this machine; Q01/Q02 need the real tag-manager project')
    python = ROOT / '.venv' / 'bin' / 'python'
    output = tmp_path_factory.mktemp('tag-manager-report') / 'report.html'
    subprocess.run([str(python if python.exists() else sys.executable), 'fastapi_visualizer.py', str(TAG_MANAGER), '-f', 'android', '-o', str(output)], cwd=ROOT, check=True, timeout=1800)
    return output


def arm(page):
    page.evaluate('() => { window.__q02 = (' + CLICK_TO_DIALOG_JS + ')(); }')


def fresh_page(chromium, html):
    context = chromium.new_context(viewport={'width': 1440, 'height': 900})
    context.set_default_timeout(15000)
    requests, errors = [], []
    context.route('http://**/*', lambda route: route.abort())
    context.route('https://**/*', lambda route: route.abort())
    context.route(CDN_URL, lambda route: route.fulfill(status=200, content_type='application/javascript', body=VIS_FILE.read_bytes()))
    context.on('request', lambda request: requests.append(request.url) if request.url.startswith(('http:', 'https:')) else None)
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    return context, page, requests, errors


def test_V09_tag_manager_graph_ready_and_modal_open_medians(chromium, tag_manager_html):
    readings = {'Q01_graph_ready_ms': [], 'Q02_modal_via_graph_click_ms': [], 'Q02_modal_via_card_click_ms': []}
    shape = {}
    for _ in range(5):
        context, page, requests, errors = fresh_page(chromium, tag_manager_html)
        try:
            start = time.perf_counter()
            page.goto(tag_manager_html.as_uri())
            page.wait_for_function(GRAPH_READY, timeout=30000)
            readings['Q01_graph_ready_ms'].append((time.perf_counter() - start) * 1000)
            data = graph_data(page)
            assert page.evaluate('JSON.parse(document.querySelector("#report-data").textContent).architecture.granularity') == 'file'
            shape = {'visible_nodes': len(data['nodes']), 'visible_edges': len(data['edges'])}
            assert shape['visible_nodes'] > 0 and shape['visible_edges'] > 0
            biggest = max(data['nodes'], key=lambda n: n['size'])['id']
            prepare_canvas(page)
            arm(page)
            click_graph_node(page, biggest)
            elapsed = page.evaluate('window.__q02')
            assert elapsed >= 0, 'dialog never became visible after the graph click'
            readings['Q02_modal_via_graph_click_ms'].append(elapsed)
            page.keyboard.press('Escape')
            card = page.locator(f'{SEL["card_group"]}[data-metric-group="pagerank"] [data-node-id]').first
            card.scroll_into_view_if_needed()
            arm(page)
            card.click()
            elapsed = page.evaluate('window.__q02')
            assert elapsed >= 0, 'dialog never became visible after the card click'
            readings['Q02_modal_via_card_click_ms'].append(elapsed)
            assert errors == [] and set(requests) <= {CDN_URL}
        finally:
            context.close()
    medians = {key: statistics.median(values) for key, values in readings.items()}
    record('tag-manager', {
        'context': 'Chromium 1440x900, five fresh contexts, CDN URL served from tests/fixtures/vis-network-9.1.9, report generated by fastapi_visualizer.py -f android',
        'html_sha256': hashlib.sha256(tag_manager_html.read_bytes()).hexdigest(), 'shape': shape, 'raw_ms': readings, 'median_ms': medians,
        'thresholds_ms': {'Q01': Q01_LIMIT_MS, 'Q02': Q02_LIMIT_MS},
        'Q01_end_marker': "document.body.dataset.graphReady === 'true' with window.ReportGraph set"})
    assert medians['Q01_graph_ready_ms'] <= Q01_LIMIT_MS, medians
    assert medians['Q02_modal_via_graph_click_ms'] <= Q02_LIMIT_MS, medians
    assert medians['Q02_modal_via_card_click_ms'] <= Q02_LIMIT_MS, medians
