"""android-nowinandroid gains Gradle build modules (spec 09e1bf05d439475e G3), so its outputs no longer match the base hashes.
The base-commit facts live in build_modules_evidence/base_android-nowinandroid.json (generated by running the base commit's CLI in a
temporary git worktree: `-l kotlin --granularity file|symbol --json --bottlenecks`, PYTHONHASHSEED=0).
The checks below accept exactly the changes a build module can cause and reject anything else."""
import json
import re
from pathlib import Path

NAME = 'android-nowinandroid'
GOLDEN = Path(__file__).parent / 'build_modules_evidence' / 'base_android-nowinandroid.json'
BUILD_FILE = re.compile(r'(^|/)(build\.gradle(\.kts)?|settings\.gradle(\.kts)?|package\.json)$')
GLOBAL_FIELDS = {'pagerank', 'weighted_centrality_cost', 'betweenness_centrality'}   # graph-wide measures move when any node is added
MODULE_PREFIX = 'build-module:'


def golden():
    return json.loads(GOLDEN.read_text(encoding='utf-8'))


def is_build_file_id(ident):
    return ident.startswith('file:') and bool(BUILD_FILE.search(ident[len('file:'):]))


def is_build_artifact(ident):
    return ident.startswith(MODULE_PREFIX) or is_build_file_id(ident)


def build_packages(package_dirs):
    """Language-scheme directory packages that hold one of the given build files."""
    return {'pkg:dir:' + (ident[len('file:'):].rpartition('/')[0] or '.') for ident in package_dirs}


def assert_symbol_changes_are_build_only(payload, flags=None):
    """flags: 'android' (-f android) or 'kotlin' (-l kotlin) selects that run's base facts; None uses the -l kotlin file/symbol golden."""
    base = golden()['symbol'] if flags is None else golden()['symbol_by_flags'][flags]
    network = payload['dependency_network']
    metrics = network['node_metrics']
    added = {k for k in metrics if k not in base['node_metrics']}
    assert added and all(k.startswith(MODULE_PREFIX) for k in added), sorted(added)[:5]
    assert set(base['node_metrics']) <= set(metrics)
    assert network['node_count'] - base['node_count'] == len(added)
    assert network['edge_count'] > base['edge_count']
    for key, old in base['node_metrics'].items():
        new = metrics[key]
        differing = {f for f in old if f not in GLOBAL_FIELDS and old[f] != new[f]}
        if flags == 'android':
            # Synthesized components carry no cost and use a fallback derived from all explicit costs; the new module nodes enter that
            # statistic. Measured: one component moves by -1 token, and nodes within two hops of it by -1 hop_2_token_cost.
            allowed = {'hop_2_token_cost'} | ({'token_cost', 'effective_token_cost'} if key.startswith('component_synth_') else set())
            assert differing <= allowed and all(abs(new[f] - old[f]) <= 1 for f in differing), (key, differing)
        else:
            assert not differing, (key, differing)
    by_id = {c['id']: c for c in payload['candidates']}
    base_ids = {c['id'] for c in base['candidates']}
    assert base_ids <= set(by_id)
    for ident in set(by_id) - base_ids:
        assert str(by_id[ident].get('target')).startswith(MODULE_PREFIX), by_id[ident]['kind']
    for old in base['candidates']:
        assert (by_id[old['id']]['kind'], by_id[old['id']].get('target')) == (old['kind'], old['target'])


def assert_file_changes_are_build_only(payload):
    """Every difference against the base file-mode facts involves a build file or the `build` scheme."""
    base = golden()['file']
    network = payload['dependency_network']
    metrics = network['node_metrics']
    assert set(base['node_metrics']) <= set(metrics)
    added = {k for k in metrics if k not in base['node_metrics']}
    assert added and all(is_build_artifact(k) for k in added), sorted(added)
    for key, old in base['node_metrics'].items():
        if not is_build_artifact(key):
            differing = {f for f in old if old[f] != metrics[key][f]}
            assert differing <= GLOBAL_FIELDS, (key, differing)
    build_dirs = build_packages({k for k in metrics if is_build_file_id(k)})
    old_pm, new_pm = base['package_metrics'], network['package_metrics']
    assert set(new_pm) - set(old_pm) == {'build'}
    for scheme, rows in old_pm.items():
        assert set(rows) == set(new_pm[scheme])
        for package, row in rows.items():
            assert row == new_pm[scheme][package] or package in build_dirs, (scheme, package)
    old_pd, new_pd = base['package_dependencies'], network['package_dependencies']
    assert set(new_pd) - set(old_pd) == {'build'}
    for scheme, rows in old_pd.items():
        before = {(r['from_id'], r['to_id']): r['tier'] for r in rows}
        after = {(r['from_id'], r['to_id']): r['tier'] for r in new_pd[scheme]}
        assert before.items() <= after.items(), scheme
        for pair in set(after) - set(before):
            assert pair[0] in build_dirs or pair[1] in build_dirs, pair
    by_id = {c['id']: c for c in payload['candidates']}
    base_ids = {c['id'] for c in base['candidates']}
    assert base_ids <= set(by_id)
    for ident in set(by_id) - base_ids:
        item = by_id[ident]
        target = str(item.get('target'))
        assert (item.get('structure', {}).get('scheme') == 'build' or target.startswith(('cycle:build:', 'pkg:gradle', MODULE_PREFIX))
                or is_build_artifact(target)), (item['kind'], target)
    for old in base['candidates']:
        assert by_id[old['id']]['kind'] == old['kind'] and by_id[old['id']].get('target') == old['target']
    assert network['node_count'] - base['node_count'] == len(added)
    coverage = payload['coverage']['structure']['schemes']
    assert 'build' in coverage and coverage['build']['unassigned_file_count'] >= 0


def assert_architecture_changes_are_build_only(architecture):
    """File-mode architecture JSON: base nodes and edges all remain; the extra ones touch a build artefact or are DECLARES_DEPENDENCY."""
    base = golden()['architecture_file']
    ids = {n['id'] for n in architecture['nodes']}
    triples = {(e['from_id'], e['to_id'], e['relation']) for e in architecture['edges']}
    assert set(base['nodes']) <= ids
    assert all(is_build_artifact(i) for i in ids - set(base['nodes']))
    base_triples = {tuple(t) for t in base['edges']}
    assert base_triples <= triples
    for triple in triples - base_triples:
        assert triple[2] == 'DECLARES_DEPENDENCY' or is_build_artifact(triple[0]) or is_build_artifact(triple[1]), triple


def without_build_parts(payload):
    """Drops what a build module adds to a file-mode report, so size-style checks keep their original threshold and context."""
    base = golden()['file']
    from tests.doc_references_support import without_doc_references
    result = without_doc_references(payload)
    network = result['dependency_network']
    for key in [k for k in network['node_metrics'] if is_build_artifact(k) and k not in base['node_metrics']]:
        del network['node_metrics'][key]
    network['package_metrics'].pop('build', None)
    network['package_dependencies'].pop('build', None)
    result['coverage']['structure']['schemes'].pop('build', None)
    keep = {c['id'] for c in base['candidates']}
    result['candidates'] = [c for c in result['candidates'] if c['id'] in keep]
    return result


def assert_symbol_architecture_changes_are_build_only(architecture, flags):
    base = golden()['symbol_by_flags'][flags]['architecture']
    ids = {n['id'] for n in architecture['nodes']}
    triples = {(e['from_id'], e['to_id'], e['relation']) for e in architecture['edges']}
    assert set(base['nodes']) <= ids and all(i.startswith(MODULE_PREFIX) for i in ids - set(base['nodes']))
    base_triples = {tuple(t) for t in base['edges']}
    assert base_triples <= triples
    for triple in triples - base_triples:
        assert triple[2] == 'DECLARES_DEPENDENCY' or triple[0].startswith(MODULE_PREFIX) or triple[1].startswith(MODULE_PREFIX), triple
